"""Propagate ดาวหลายระบบด้วย GMAT เป็นตำแหน่ง EarthFixed (ECEF) แล้วอ่านผลเป็น Ephemeris (หัวข้อ 5.7 ของ spec engine)

- ไฟล์ TLE ของรอบนี้ใช้ PRN เป็นบรรทัดชื่อ และ script ตั้ง `Spacecraft.Id` เป็น PRN เพราะ GMAT TLEReader
  หาดาวจากบรรทัดชื่อ ไม่ขึ้นกับหมายเลขแคตตาล็อก (Alpha-5 เช่น A0744 ก็ใช้ได้)
- GMAT ต้องการหนึ่งคำสั่งต่อบรรทัด (หลายคำสั่งคั่นด้วย `;` ในบรรทัดเดียวจะ error "Cannot create an object")
- ตารางเวลาคือ start + k·step_s สำหรับ k = 0..(stop − start)/step_s รวมทั้งต้นและปลาย
  start/stop ต้องเป็นวินาทีเต็มและ (stop − start) หารด้วย step_s ลงตัว (scenario.py ตรวจให้แล้ว)
  ถ้าไม่เป็นเช่นนั้นถือเป็นความผิดของผู้เรียก (ValueError)
- parse_ecef_report และ propagate คืน (Ephemeris, list[Message]) ตาม D3
"""

import csv
import math
from time import monotonic
from collections.abc import Callable
from dataclasses import dataclass
from datetime import datetime, timedelta, timezone
from pathlib import Path

from .catalog import CatalogSatellite
from .config import GPS_UTC_OFFSET_S
from .errors import GmatRunError, Message, ReportError, Sp3FormatError
from .gmat_time import format_gmat_epoch, parse_gmat_epoch
from .run_gmat import run_script
from .sp3 import read_sp3_all

TLE_NAME = "all.tle"
SCRIPT_NAME = "ecef.script"
REPORT_NAME = "ecef_report.txt"
LOG_NAME = "gmat.log"
GMAT_BATCH_SIZE = 64

Position = tuple[float, float, float]


@dataclass
class Ephemeris:
    times_utc: list[datetime]
    positions_km: dict[str, list[Position]]      # PRN → ตำแหน่ง ECEF (กม.) ต่อเวลา


def _grid(start: datetime, stop: datetime, step_s: int) -> list[datetime]:
    """start + k·step_s จนถึง stop (รวมทั้งสองปลาย) เป็นเวลา UTC"""
    if isinstance(step_s, bool) or not isinstance(step_s, int) or step_s < 1:
        raise ValueError(f"step_s ต้องเป็นจำนวนเต็มบวก ได้ {step_s!r}")
    start = start.astimezone(timezone.utc)
    stop = stop.astimezone(timezone.utc)
    if start.microsecond or stop.microsecond:
        raise ValueError("start และ stop ต้องเป็นวินาทีเต็ม")
    span_s = int((stop - start).total_seconds())
    if span_s <= 0 or span_s % step_s:
        raise ValueError(f"stop − start ({span_s} วินาที) ต้องเป็นบวกและหารด้วย step_s ({step_s}) ลงตัว")
    return [start + timedelta(seconds=k * step_s) for k in range(span_s // step_s + 1)]


def _round_to_second(t: datetime) -> datetime:
    # GMAT อาจเขียนเวลาคลาดเล็กน้อย เช่น 00:00:29.999 แทน 00:00:30.000 (เหมือน report.py เดิม)
    return (t + timedelta(microseconds=500_000)).replace(microsecond=0)


def write_tle_file(sats: list[CatalogSatellite], path: Path) -> None:
    """ไฟล์ TLE แบบ 3 บรรทัดต่อดวง บรรทัดชื่อคือ PRN"""
    text = "".join(f"{s.prn}\n{s.tle_lines[0]}\n{s.tle_lines[1]}\n" for s in sats)
    with open(path, "w", encoding="ascii", newline="\n") as f:
        f.write(text)


def render_ecef_script(sats: list[CatalogSatellite], tle_path: Path, start: datetime,
                       stop: datetime, step_s: int, report_path: Path) -> str:
    """GMAT script ที่ propagate ทุกดวงพร้อมกัน และเขียนรายงานตำแหน่ง EarthFixed ลง report_path"""
    if not sats:
        raise ValueError("ไม่มีดาวให้สร้าง script")
    _grid(start, stop, step_s)
    prns = [s.prn for s in sats]
    epoch = format_gmat_epoch(start)
    elapsed_s = int((stop - start).total_seconds())
    columns = [f"{prns[0]}.UTCGregorian"] + [f"{p}.EarthFixed.{axis}" for p in prns for axis in "XYZ"]
    lines = ["% EarthFixed positions of GNSS satellites from TLE (SGP4), generated by gnss_predict"]
    for prn in prns:
        lines += [f"Create Spacecraft {prn};",
                  f"{prn}.DateFormat = UTCGregorian;",
                  f"{prn}.Epoch = '{epoch}';",
                  f"{prn}.Id = '{prn}';",
                  f"{prn}.EphemerisName = '{tle_path}';"]
    lines += ["Create Propagator TLEProp;",
              "TLEProp.Type = SPICESGP4;",
              f"TLEProp.InitialStepSize = {step_s};",
              "Create ReportFile RF;",
              f"RF.Filename = '{report_path}';",
              "RF.Precision = 16;",
              "RF.WriteHeaders = true;",
              "RF.FixedWidth = false;",
              "RF.Delimiter = ',';",
              f"RF.Add = {{{', '.join(columns)}}};",
              "BeginMissionSequence;",
              f"Propagate TLEProp({', '.join(prns)}) {{{prns[0]}.ElapsedSecs = {elapsed_s}}};"]
    return "\n".join(lines) + "\n"


def _missing(prn: str, why: str) -> Message:
    return Message("SAT_MISSING_FROM_GMAT", "warning",
                   f"ตัดดาว {prn} ออก: {why} ในรายงานของ GMAT", prn)


def parse_ecef_report(path: Path, prns: list[str], start: datetime, stop: datetime,
                      step_s: int) -> tuple[Ephemeris, list[Message]]:
    """อ่านรายงานของ GMAT เป็น Ephemeris

    ปัดเวลาเป็นวินาที ข้ามแถวที่เวลาซ้ำ (GMAT อาจเขียนแถวสุดท้ายซ้ำ) แล้วตรวจว่าเวลาเรียงครบตาม grid พอดี
    ไม่ครบหรือเกินหรือไม่เรียง -> ReportError ดวงที่ไม่มีคอลัมน์ครบ 3 แกนหรือมีค่าที่ไม่ใช่ตัวเลข
    ถูกตัดออกพร้อม Message SAT_MISSING_FROM_GMAT
    """
    path = Path(path)
    grid = _grid(start, stop, step_s)
    if not path.is_file():
        raise ReportError(f"ไม่พบไฟล์รายงานของ GMAT: {path}")
    with open(path, newline="", encoding="utf-8", errors="replace") as f:
        rows = [r for r in csv.reader(f) if any(c.strip() for c in r)]
    if not rows:
        raise ReportError(f"ไฟล์รายงานว่าง: {path}")
    col = {h.strip(): i for i, h in enumerate(rows[0])}
    time_col = next((i for h, i in col.items() if h.endswith(".UTCGregorian")), None)
    if time_col is None:
        raise ReportError(f"รายงานไม่มีคอลัมน์ *.UTCGregorian: {path.name}")

    messages: list[Message] = []
    columns: dict[str, list[int]] = {}
    for prn in dict.fromkeys(prns):
        names = [f"{prn}.EarthFixed.{axis}" for axis in "XYZ"]
        absent = [n for n in names if n not in col]
        if absent:
            messages.append(_missing(prn, f"ไม่มีคอลัมน์ {', '.join(absent)}"))
        else:
            columns[prn] = [col[n] for n in names]

    values: dict[str, list[Position]] = {prn: [] for prn in columns}
    times: list[datetime] = []
    seen: set[datetime] = set()
    for lineno, row in enumerate(rows[1:], start=2):
        try:
            t = _round_to_second(parse_gmat_epoch(row[time_col].strip()))
        except (ValueError, IndexError) as exc:
            raise ReportError(f"{path.name} บรรทัด {lineno} อ่านเวลาไม่ได้: {exc}") from exc
        if t in seen:
            continue
        seen.add(t)
        times.append(t)
        for prn in list(values):
            try:
                xyz = tuple(float(row[i]) for i in columns[prn])
            except (ValueError, IndexError):
                xyz = None
            if xyz is None or not all(math.isfinite(v) for v in xyz):
                messages.append(_missing(prn, f"ค่าที่บรรทัด {lineno} ไม่ใช่ตัวเลข"))
                del values[prn]
            else:
                values[prn].append(xyz)

    if times != grid:
        expected = set(grid)
        absent = [t for t in grid if t not in seen]
        extra = sorted(seen - expected)
        if absent:
            raise ReportError(f"{path.name}: ไม่มี epoch {absent[0].isoformat()} (ขาด {len(absent)} epoch)")
        if extra:
            raise ReportError(f"{path.name}: มี epoch เกินมา {extra[0].isoformat()} ({len(extra)} epoch)")
        raise ReportError(f"{path.name}: epoch ไม่เรียงตามเวลา")
    return Ephemeris(grid, values), messages


def propagate(sats: list[CatalogSatellite], start: datetime, stop: datetime, step_s: int,
              work_dir: Path, console: Path, timeout_s: float = 900,
              on_gmat_start: Callable[[int], None] | None = None) -> tuple[Ephemeris, list[Message]]:
    """เขียน all.tle และ ecef.script ใน work_dir, รัน GMAT แล้วอ่านรายงาน

    on_gmat_start(pgid) ส่งต่อให้ run_script เป็น on_start (process group id ของ GMAT สำหรับยกเลิกงาน)
    """
    _grid(start, stop, step_s)                      # ตรวจก่อนเสียเวลารัน GMAT
    work_dir = Path(work_dir).resolve()
    work_dir.mkdir(parents=True, exist_ok=True)
    if len(sats) > GMAT_BATCH_SIZE:
        # Bound GMAT script/report width; all batches share the exact same UTC grid.
        positions, messages = {}, []
        grid = _grid(start, stop, step_s)
        deadline = monotonic() + timeout_s
        for offset in range(0, len(sats), GMAT_BATCH_SIZE):
            remaining_s = deadline - monotonic()
            if remaining_s <= 0:
                raise GmatRunError("หมดเวลาคำนวณ GMAT ของดาวหลายชุด")
            batch_dir = work_dir / f"batch-{offset // GMAT_BATCH_SIZE + 1:03d}"
            eph, batch_messages = propagate(sats[offset:offset + GMAT_BATCH_SIZE], start, stop, step_s,
                                            batch_dir, console, remaining_s, on_gmat_start)
            if eph.times_utc != grid or positions.keys() & eph.positions_km.keys():
                raise ReportError("ผล GMAT แต่ละชุดมีเวลาไม่ตรงกันหรือรหัสดาวซ้ำ")
            positions.update(eph.positions_km)
            messages.extend(batch_messages)
        return Ephemeris(grid, positions), messages
    tle_path = work_dir / TLE_NAME
    script_path = work_dir / SCRIPT_NAME
    report_path = work_dir / REPORT_NAME
    write_tle_file(sats, tle_path)
    script_path.write_text(render_ecef_script(sats, tle_path, start, stop, step_s, report_path), encoding="utf-8")
    report_path.unlink(missing_ok=True)             # กันอ่านรายงานเก่าของรอบก่อนถ้า GMAT ไม่ได้เขียนใหม่
    hook = {} if on_gmat_start is None else {"on_start": on_gmat_start}
    run_script(console, script_path, work_dir / LOG_NAME, timeout_s, **hook)
    return parse_ecef_report(report_path, [s.prn for s in sats], start, stop, step_s)


def ephemeris_from_sp3(path: Path) -> Ephemeris:
    """อ่าน predicted.sp3 (เวลา GPST) แล้วลบ GPS_UTC_OFFSET_S กลับเป็น UTC

    ทุกดวงต้องมีตำแหน่งครบทุก epoch ไม่งั้น Sp3FormatError (ไฟล์ที่ engine เขียนเองต้องครบ)
    """
    path = Path(path)
    series = read_sp3_all(path)
    times_gpst = sorted({t for s in series.values() for t in s})
    if not times_gpst:
        raise Sp3FormatError(f"{path.name}: ไม่มีตำแหน่งดาวในไฟล์")
    positions: dict[str, list[Position]] = {}
    for prn, s in series.items():
        if len(s) != len(times_gpst):
            raise Sp3FormatError(f"{path.name}: ดาว {prn} มีตำแหน่ง {len(s)} จาก {len(times_gpst)} epoch")
        positions[prn] = [s[t] for t in times_gpst]
    offset = timedelta(seconds=GPS_UTC_OFFSET_S)
    return Ephemeris([t - offset for t in times_gpst], positions)
