// สร้าง src/api/enums.gen.ts จาก schema ของ ScenarioDoc ใน src/api/openapi.json (ไม่พิมพ์ค่าเองสักตัว)
// Literal ใน server/gnss_studio_server/schema.py ถูก pydantic ใส่ inline ในแต่ละ property จึงหาค่าด้วย model + property
// ถ้าชื่อ model หรือ property เปลี่ยนไปจน enum หาย สคริปต์หยุดพร้อมบอกว่าขาดอะไร ไม่เขียนไฟล์ครึ่งๆ กลางๆ
import { readFileSync, writeFileSync } from "node:fs";
import { SOURCES } from "./enum-sources.mjs";   // ชื่อใน ENUMS -> model + property ที่ประกาศ Literal

const SPEC = new URL("../src/api/openapi.json", import.meta.url);
const OUT = new URL("../src/api/enums.gen.ts", import.meta.url);

const spec = JSON.parse(readFileSync(SPEC, "utf8"));
const schemas = spec.components?.schemas ?? {};

function resolve(schema) {
  if (schema?.$ref) {
    const name = schema.$ref.replace("#/components/schemas/", "");
    if (!schemas[name]) throw new Error(`$ref ${schema.$ref} not found`);
    return resolve(schemas[name]);
  }
  return schema;
}

/** enum ของ property: อ่านได้ทั้งแบบ inline, ผ่าน $ref, และแบบ `X | None` (anyOf ที่มี null)
 * Literal ค่าเดียว (เช่น "Simple Conic") pydantic ใส่เป็น `const` ไม่ใช่ `enum` นับเป็น enum ที่มีค่าเดียว */
function enumsIn(schema) {
  const s = resolve(schema);
  if (!s) return [];
  if (Array.isArray(s.enum)) return [s.enum];
  if (typeof s.const === "string") return [[s.const]];
  if (Array.isArray(s.anyOf)) return s.anyOf.flatMap(enumsIn);
  return [];
}

function enumAt(model, prop) {
  const property = schemas[model]?.properties?.[prop];
  if (!property) throw new Error(`schema ${model}.${prop} not found in src/api/openapi.json`);
  const found = enumsIn(property);
  if (found.length !== 1 || !found[0].every((v) => typeof v === "string"))
    throw new Error(`${model}.${prop} must carry exactly one enum of strings, found ${JSON.stringify(found)}`);
  return found[0];
}

const enums = {};
for (const [key, [model, prop, same = []]] of Object.entries(SOURCES)) {
  enums[key] = enumAt(model, prop);
  for (const [otherModel, otherProp] of same)
    if (JSON.stringify(enumAt(otherModel, otherProp)) !== JSON.stringify(enums[key]))
      throw new Error(`${key}: ${model}.${prop} and ${otherModel}.${otherProp} disagree`);
}

const body = Object.entries(enums)
  .map(([key, values]) => `  ${key}: [${values.map((v) => JSON.stringify(v)).join(", ")}],`)
  .join("\n");

writeFileSync(OUT, `/**
 * This file was auto-generated by tools/gen-enums.mjs from src/api/openapi.json.
 * Do not make direct changes to the file.
 */

export const ENUMS = {
${body}
} as const;
`);
